-- V3: RTSP IP Camera Stream Registry
-- Stores registered IP cameras, their RTSP endpoints, and associated road segments

CREATE TABLE IF NOT EXISTS camera_streams (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stream_id    VARCHAR(50)  UNIQUE NOT NULL,
    rtsp_url     VARCHAR(500) NOT NULL,
    segment_id   VARCHAR(10)  NOT NULL,
    location_lat DOUBLE PRECISION,
    location_lng DOUBLE PRECISION,
    label        VARCHAR(150),
    fps_sample   INTEGER      NOT NULL DEFAULT 2,
    enabled      BOOLEAN      NOT NULL DEFAULT TRUE,
    last_seen_at TIMESTAMP WITH TIME ZONE,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

