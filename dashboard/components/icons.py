def render_metric_card(label: str, value: str, subtext: str = "", status: str = "neutral") -> str:
    color_map = {
        "primary": "#0284C7",
        "success": "#059669",
        "warning": "#D97706",
        "danger": "#DC2626",
        "neutral": "#64748B"
    }
    sub_color = color_map.get(status, "#64748B")
    return f"""
    <div class="metric-card">
        <div class="metric-label">{label}</div>
        <div class="metric-value">{value}</div>
        {f'<div class="metric-subtext" style="color:{sub_color};">{subtext}</div>' if subtext else ''}
    </div>
    """


def render_stepper(current_step: int = 1) -> str:
    steps = [
        ("1. Dispatch", "108 Call Received"),
        ("2. Base Route", "Initial Dijkstra"),
        ("3. Congestion", "YOLOv8 Detection"),
        ("4. Re-Route", "Hysteresis Delta"),
        ("5. Preemption", "ESP32 Safe Phase"),
        ("6. Trauma Bay", "Patient Handover")
    ]
    html = '<div class="stepper-container">'
    for idx, (title, desc) in enumerate(steps, 1):
        if idx < current_step:
            circle_cls = "step-circle step-circle-done"
            symbol = "✓"
        elif idx == current_step:
            circle_cls = "step-circle step-circle-active"
            symbol = str(idx)
        else:
            circle_cls = "step-circle"
            symbol = str(idx)

        html += f"""
        <div class="step-node">
            <div class="{circle_cls}">{symbol}</div>
            <div class="step-title">{title}</div>
            <div class="step-desc">{desc}</div>
        </div>
        """
        if idx < len(steps):
            line_color = "#10B981" if idx < current_step else ("#0284C7" if idx == current_step else "#E2E8F0")
            html += f'<div style="flex:1; height:2px; background:{line_color}; margin:0 8px; margin-bottom:18px;"></div>'

    html += '</div>'
    return html


